from django.conf import settings
from rest_framework.decorators import api_view, permission_classes, authentication_classes
from rest_framework.permissions import AllowAny, IsAuthenticated
from rest_framework.response import Response
from rest_framework import status
from drf_spectacular.utils import extend_schema, OpenApiResponse, OpenApiParameter, inline_serializer
from rest_framework import serializers

from apps.payments.serializers import (
    PaymentRequestCreateSerializer,
    PaymentRequestUpdateSerializer,
    PaymentRequestDetailSerializer,
    PublicCheckoutSerializer,
)
from apps.payments.services import (
    create_payment_request_service,
    get_payment_request_by_ref_service,
    cancel_payment_request_service,
    update_payment_request_service,
)
from apps.payments.models import PaymentRequest
from apps.merchants.models import Merchant

@extend_schema(
    tags=['Payments'],
    summary='Generate a new payment request / invoice',
    description='Generates a new payment request with amount, USDC Testnet/XLM, unique memo, SEP-0007 URI, and QR code for customer checkout.',
    request=PaymentRequestCreateSerializer,
    responses={
        201: inline_serializer(
            name='PaymentCreateResponse',
            fields={
                'success': serializers.BooleanField(default=True),
                'message': serializers.CharField(),
                'data': PaymentRequestDetailSerializer(),
            }
        ),
        400: OpenApiResponse(description='Validation error or wallet not connected'),
    }
)
@api_view(['POST'])
@permission_classes([IsAuthenticated])
def create_payment_request_view(request):
    """Function-based view for creating a payment request."""
    try:
        merchant = request.user.merchant_profile
    except Merchant.DoesNotExist:
        return Response({
            'success': False,
            'message': 'Authenticated user is not registered as a merchant.',
        }, status=status.HTTP_404_NOT_FOUND)

    serializer = PaymentRequestCreateSerializer(data=request.data)
    serializer.is_valid(raise_exception=True)

    payment_request = create_payment_request_service(
        merchant=merchant,
        data=serializer.validated_data,
        request_obj=request
    )

    return Response({
        'success': True,
        'message': 'Payment request created successfully.',
        'data': PaymentRequestDetailSerializer(payment_request).data,
    }, status=status.HTTP_201_CREATED)

@extend_schema(
    tags=['Payments'],
    operation_id='merchant_list_payment_requests',
    summary='List merchant payment requests',
    description='Returns a list of all payment requests generated by the authenticated merchant, with optional status filter.',
    parameters=[
        OpenApiParameter(name='status', type=str, required=False, description='Filter by status: PENDING, COMPLETED, EXPIRED, CANCELLED'),
        OpenApiParameter(name='currency', type=str, required=False, description='Filter by currency: USDC, XLM'),
    ],
    responses={
        200: inline_serializer(
            name='PaymentListResponse',
            fields={
                'success': serializers.BooleanField(default=True),
                'count': serializers.IntegerField(),
                'results': PaymentRequestDetailSerializer(many=True),
            }
        )
    }
)
@api_view(['GET', 'POST'])
@permission_classes([IsAuthenticated])
def list_payment_requests_view(request):
    """Function-based view to list or create payment requests for the merchant."""
    if request.method == 'POST':
        return create_payment_request_view(request)

    merchant = request.user.merchant_profile
    queryset = PaymentRequest.objects.filter(merchant=merchant).order_by('-created_at')

    status_filter = request.query_params.get('status')
    if status_filter:
        queryset = queryset.filter(status=status_filter.upper())

    currency_filter = request.query_params.get('currency')
    if currency_filter:
        queryset = queryset.filter(currency=currency_filter.upper())

    paginator = request.pagination_class() if hasattr(request, 'pagination_class') and request.pagination_class else None
    if paginator:
        page = paginator.paginate_queryset(queryset, request)
        serializer = PaymentRequestDetailSerializer(page, many=True)
        return paginator.get_paginated_response(serializer.data)

    serializer = PaymentRequestDetailSerializer(queryset, many=True)
    return Response({
        'success': True,
        'count': queryset.count(),
        'results': serializer.data,
    })

@extend_schema(
    tags=['Payments'],
    operation_id='merchant_get_or_update_payment_request_detail',
    summary='Get or edit payment request details',
    description='Retrieve or update detailed information of a specific payment request by reference ID.',
    request=PaymentRequestUpdateSerializer,
    responses={
        200: inline_serializer(
            name='PaymentDetailResponse',
            fields={
                'success': serializers.BooleanField(default=True),
                'message': serializers.CharField(required=False),
                'data': PaymentRequestDetailSerializer(),
            }
        ),
        400: OpenApiResponse(description='Validation error'),
        404: OpenApiResponse(description='Payment request not found'),
    }
)
@api_view(['GET', 'PUT', 'PATCH'])
@permission_classes([IsAuthenticated])
def payment_request_detail_view(request, reference_id):
    """Function-based view to retrieve or update a payment request detail."""
    merchant = request.user.merchant_profile

    if request.method in ['PUT', 'PATCH']:
        serializer = PaymentRequestUpdateSerializer(data=request.data, partial=True)
        serializer.is_valid(raise_exception=True)
        try:
            payment_request = update_payment_request_service(
                merchant=merchant,
                reference_id=reference_id,
                data=serializer.validated_data,
                request_obj=request,
            )
        except Exception as e:
            return Response({
                'success': False,
                'message': str(e),
            }, status=status.HTTP_400_BAD_REQUEST)

        return Response({
            'success': True,
            'message': 'Payment request updated successfully.',
            'data': PaymentRequestDetailSerializer(payment_request).data,
        }, status=status.HTTP_200_OK)

    # GET
    try:
        payment_request = PaymentRequest.objects.get(merchant=merchant, reference_id=reference_id)
    except PaymentRequest.DoesNotExist:
        return Response({
            'success': False,
            'message': f"Payment request '{reference_id}' was not found.",
        }, status=status.HTTP_404_NOT_FOUND)

    return Response({
        'success': True,
        'data': PaymentRequestDetailSerializer(payment_request).data,
    })

@extend_schema(
    tags=['Payments'],
    operation_id='merchant_cancel_payment_request',
    summary='Cancel a pending payment request',
    description='Cancel an unpaid payment request before it expires or is settled.',
    request=None,
    responses={
        200: inline_serializer(
            name='PaymentCancelResponse',
            fields={
                'success': serializers.BooleanField(default=True),
                'message': serializers.CharField(),
                'data': PaymentRequestDetailSerializer(),
            }
        )
    }
)
@api_view(['POST'])
@permission_classes([IsAuthenticated])
def cancel_payment_request_view(request, reference_id):
    """Function-based view to cancel a pending payment request."""
    merchant = request.user.merchant_profile
    payment_request = cancel_payment_request_service(merchant, reference_id)

    return Response({
        'success': True,
        'message': f"Payment request '{reference_id}' has been cancelled.",
        'data': PaymentRequestDetailSerializer(payment_request).data,
    })

@extend_schema(
    tags=['Checkout'],
    summary='Public customer checkout view',
    description='Public endpoint for customers to review merchant details, amount, USDC Testnet asset, memo, and receive SEP-0007 / QR code payload.',
    responses={
        200: inline_serializer(
            name='CustomerCheckoutResponse',
            fields={
                'success': serializers.BooleanField(default=True),
                'data': PublicCheckoutSerializer(),
            }
        ),
        404: OpenApiResponse(description='Invoice not found'),
    }
)
@api_view(['GET'])
@authentication_classes([])
@permission_classes([AllowAny])
def public_checkout_view(request, reference_id):
    """Public customer checkout view for loading payment request details."""
    accept = request.META.get('HTTP_ACCEPT', '')
    if 'text/html' in accept and 'application/json' not in accept:
        base_checkout = getattr(settings, 'SMEHUB_BASE_CHECKOUT_URL', 'http://localhost:3000/checkout/').rstrip('/')
        from django.http import HttpResponseRedirect
        return HttpResponseRedirect(f"{base_checkout}/{reference_id}")

    req = get_payment_request_by_ref_service(reference_id)
    return Response({
        'success': True,
        'message': 'Payment request details retrieved for customer checkout.',
        'data': PublicCheckoutSerializer(req).data,
    }, status=status.HTTP_200_OK)
