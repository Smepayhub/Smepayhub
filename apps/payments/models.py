import secrets
from django.db import models
from django.utils import timezone
from apps.core.models import BaseModel
from apps.merchants.models import Merchant

class PaymentStatus(models.TextChoices):
    PENDING = 'PENDING', 'Pending Payment'
    COMPLETED = 'COMPLETED', 'Payment Completed'
    EXPIRED = 'EXPIRED', 'Payment Request Expired'
    CANCELLED = 'CANCELLED', 'Cancelled by Merchant'
    FAILED = 'FAILED', 'Payment Failed'

class PaymentAsset(models.TextChoices):
    USDC = 'USDC', 'USD Coin (Stellar Testnet)'
    XLM = 'XLM', 'Stellar Lumens (Native)'

class PaymentRequest(BaseModel):
    """Payment Request / Invoice generated by a merchant for customer checkout."""
    merchant = models.ForeignKey(Merchant, on_delete=models.CASCADE, related_name='payment_requests')
    reference_id = models.CharField(max_length=32, unique=True, db_index=True)
    order_reference = models.CharField(max_length=32, blank=True, default='', db_index=True, help_text="Auto-generated unique merchant order reference")
    orders = models.JSONField(default=list, blank=True, help_text="Itemized order choices with title, unit price, quantity, and subtotal")
    memo = models.CharField(max_length=28, unique=True, db_index=True, help_text="Unique Stellar transaction memo for matching")
    amount = models.DecimalField(max_digits=18, decimal_places=4)
    currency = models.CharField(max_length=10, choices=PaymentAsset.choices, default=PaymentAsset.USDC)
    asset_issuer = models.CharField(max_length=56, blank=True, null=True)
    destination_address = models.CharField(max_length=56, help_text="Merchant's receiving Stellar public key")
    status = models.CharField(max_length=20, choices=PaymentStatus.choices, default=PaymentStatus.PENDING, db_index=True)
    title = models.CharField(max_length=255, default='Payment Request')
    description = models.TextField(blank=True, default='')
    customer_name = models.CharField(max_length=255, blank=True, default='')
    customer_email = models.EmailField(blank=True, null=True)
    sep0007_uri = models.TextField(blank=True, default='', help_text="Stellar SEP-0007 pay URI for wallets")
    checkout_url = models.URLField(max_length=500, blank=True, default='')
    qr_code_base64 = models.TextField(blank=True, default='', help_text="Base64 Data URI PNG for QR code")
    expires_at = models.DateTimeField(db_index=True)
    paid_at = models.DateTimeField(null=True, blank=True)

    class Meta(BaseModel.Meta):
        verbose_name = 'Payment Request'
        verbose_name_plural = 'Payment Requests'

    def is_expired(self) -> bool:
        """Check if request has expired and is still in PENDING state."""
        return self.status == PaymentStatus.PENDING and timezone.now() > self.expires_at

    def __str__(self):
        return f"{self.reference_id} - {self.amount} {self.currency} ({self.status})"
